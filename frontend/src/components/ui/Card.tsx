import React from "react";
import { cn } from "../../utils/cn";

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  interactive?: boolean;
}

export const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, interactive, children, ...props }, ref) => {
    return (
      <div
        ref={ref}
        className={cn(
          "rounded-xl bg-[var(--bg-card)] border border-[var(--border-app)] shadow-lg shadow-black/10 dark:shadow-black/40 overflow-hidden transition-[background-color,border-color] duration-150",
          interactive &&
            "ease-out hover:bg-[var(--bg-card-hover)] hover:border-indigo-500/30 cursor-pointer",
          className
        )}
        {...props}
      >
        {children}
      </div>
    );
  }
);
Card.displayName = "Card";

